def load_font():
    """FONT_TEXT as a dict: character -> 8 rows of 8."""
    font = {' ': ['........'] * 8}
    lines = [ln for ln in FONT_TEXT.split('\n') if ln]
    for i in range(0, len(lines), 8):
        ch, rows = lines[i], lines[i + 1:i + 8] + ['........']
        if len(ch) != 1 or any(len(r) != 8 for r in rows):
            raise ValueError(f'font: bad glyph {ch!r}')
        font[ch] = rows
    return font


